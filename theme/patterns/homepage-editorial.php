<h2 class="wp-block-heading">پرسش‌های متداول</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>پاسخ کوتاه به سؤال‌هایی که بیشتر هنرجویان پیش از ثبت‌نام دارند.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"className":"dzn-faq__list","layout":{"type":"default"}} -->
<div class="wp-block-group dzn-faq__list"><!-- wp:details -->
<details class="wp-block-details"><summary><strong>از چه کشورهایی می‌توانم در کلاس‌های دلنوازان شرکت کنم؟</strong></summary><!-- wp:paragraph -->
<p>کلاس‌های آنلاین دلنوازان برای ایرانیان سراسر جهان طراحی شده است و محدودیت جغرافیایی ندارد. هنرجویان ما از کشورهایی مانند استرالیا، نیوزیلند، آمریکا، کانادا، انگلستان و بسیاری از کشورهای اروپایی در این کلاس‌ها شرکت می‌کنند. بنابراین اگر به دنبال <strong>آموزش موسیقی برای ایرانیان آمریکا، کانادا، اروپا یا استرالیا</strong> هستید، می‌توانید به‌راحتی از هر نقطه دنیا در کلاس‌های آنلاین دلنوازان ثبت‌نام کنید.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary><strong>اگر هنوز ساز ندارم چه کنم؟</strong></summary><!-- wp:paragraph -->
<p> دلنوازان می‌تواند در تهیه و ارسال ساز، کتاب‌های آموزشی و لوازم مورد نیاز به صورت یک پکیج کامل به شما کمک کند. پس از ثبت‌نام، تا زمان دریافت بسته آموزشی، جلسات رسمی شما آغاز نخواهد شد تا هیچ بخشی از آموزش را از دست ندهید. در این مدت نیز می‌توانید با راهنمایی استاد، مقدمات کار و مباحث تئوری را دنبال کنید و پس از دریافت ساز، آموزش عملی را به‌صورت رسمی آغاز نمایید.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>این سرویس به منظور راحتی هنرجو و دسترسی آسان به ساز ارائه شده است و وبسایت دلنوازان به طور مستقیم فروشگاه ساز ندارد</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary><strong>من هیچ پیش‌زمینه‌ای در موسیقی ندارم. آیا می‌توانم از طریق آموزش‌های آنلاین موسیقی یاد بگیرم؟</strong></summary><!-- wp:paragraph -->
<p>نداشتن هیچ پیش‌زمینه‌ای در موسیقی نه‌تنها مانع نیست، بلکه یکی از رایج‌ترین نقطه‌های شروع هنرجویان ماست. تفاوت آموزش آنلاین با آموزش حضوری صرفاً در «غیرحضوری بودن» آن است و از نظر محتوای آموزشی، کیفیت تدریس و روند یادگیری، هیچ تفاوت ماهوی دیگری وجود ندارد.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>در کلاس‌های آنلاین، دقیقاً همان سرفصل‌ها و متدهایی تدریس می‌شود که در آموزش حضوری ارائه می‌گردد. استاد با استفاده از کتاب‌ها و منابع استاندارد آموزشی، درس‌ها را به‌صورت مرحله‌به‌مرحله پیش می‌برد و هنرجو به‌آرامی و اصولی مسیر یادگیری را طی می‌کند. در طول کلاس، استاد به‌صورت زنده اجرای شما را می‌بیند، اشکالاتتان را اصلاح می‌کند، نکات تکنیکی لازم را توضیح می‌دهد و شما را متناسب با سطح‌تان راهنمایی می‌کند.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>تجربه آکادمی دلنوازان نشان داده است که بسیاری از هنرجویانی که آموزش را بدون هیچ دانشی از موسیقی آغاز کرده‌اند، با آموزش آنلاین به پیشرفت‌های چشمگیر و حتی سطح حرفه‌ای رسیده‌اند. آنچه بیش از هر چیز در پیشرفت شما نقش دارد، میزان تمرین منظم، کیفیت تمرین و زمانی است که برای کار با ساز خود اختصاص می‌دهید؛ نه این‌که کلاس به‌صورت حضوری برگزار شود یا آنلاین.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>بنابراین اگر به هر دلیلی امکان شرکت در کلاس‌های حضوری را ندارید، آموزش آنلاین یک گزینه‌ی کاملاً مؤثر، حرفه‌ای و قابل‌اعتماد است و می‌توانید با پشتکار و تمرین مستمر، به نتایج بسیار خوبی دست پیدا کنید<strong>.</strong></p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary><strong>استادان شما چه کسانی هستند؟ می‌توانیم نمونه کار استادها را ببینیم؟</strong></summary><!-- wp:paragraph -->
<p>برای حفظ کیفیت و روند آموزشی، معرفی استاد و برگزاری جلسه آشنایی پس از ثبت‌نام انجام می‌شود. خوشبختانه ثبت‌نام اولیه و جلسه معارفه کاملاً رایگان است و شما پیش از پرداخت هرگونه هزینه، با استاد خود آشنا می‌شوید و می‌توانید درباره شیوه تدریس و برنامه آموزشی گفت‌وگو کنید. در صورت عدم تمایل به ادامه کلاس، امکان لغو بدون هیچ هزینه‌ای وجود دارد.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary><strong>اگر یک جلسه را غیبت کنم چه می‌شود؟</strong></summary><!-- wp:paragraph -->
<p>در این مورد، استاد می‌تواند برای شما&nbsp;<strong>جلسه جبرانی</strong>&nbsp;برگزار کند. هر ترم شما می توانید دو جلسه جبرانی داشته باشید که باید قبل از پایان ترم برگزار شوند.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary><strong>برنامه کاری/تحصیلی من اجازه شرکت در کلاس ها با روز و زمان ثابت را نمی دهد؟ راه حلی دارید؟</strong></summary><!-- wp:paragraph -->
<p>اگر نمی‌توانید هر هفته در روز و ساعت ثابت کلاس داشته باشید، بعد از ثبت‌نام و&nbsp;جلسه معرفی، می‌توانید با استاد برای کلاس های متغییر هماهنگ کنید.<br>اساتید بر اساس برنامه خودشان،&nbsp;روزها و ساعت‌های متغیر&nbsp;را با شما تنظیم می‌کنند و ما آن را در سایت وارد می‌کنیم.</p>
